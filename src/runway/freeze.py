"""One launch calendar, three enforcers.

* The wave planner skips maintenance windows that touch a freeze (plan.py).
* Argo CD refuses to sync during a freeze: deny sync windows on the AppProject of each site.
* GitLab CI refuses to deploy during a freeze: deploy freeze periods (CI_DEPLOY_FREEZE) and a
  freeze gate job that asks this module, with an audited emergency override.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any
from zoneinfo import ZoneInfo

from runway import calendar
from runway.settings import Campaign, Windows


def _cron(dt: datetime) -> str:
    return f"{dt.minute} {dt.hour} {dt.day} {dt.month} *"


def _hours(c: Campaign) -> str:
    return f"{round((c.freeze_end - c.freeze_start).total_seconds() / 3600)}h"


def window_names(w: Windows, site_clusters: dict[str, list[str]], now: datetime) -> dict[str, str]:
    """Which campaign each generated window belongs to, by schedule (Argo CD windows carry no name)."""
    tz = ZoneInfo(w.timezone)
    return {_cron(c.freeze_start.astimezone(tz)): c.name for c in w.campaigns if c.freeze_end > now}


def argocd_sync_windows(w: Windows, site_clusters: dict[str, list[str]], now: datetime) -> list[dict[str, Any]]:
    """Deny windows for every freeze that has not ended. Argo CD schedules are cron + duration, so a
    one-off freeze is written as a yearly cron with the freeze's start; ended freezes are dropped so
    the window does not come back next year."""
    tz = ZoneInfo(w.timezone)
    out = []
    for c in sorted(w.campaigns, key=lambda c: c.freeze_start):
        if c.freeze_end <= now:
            continue
        start = c.freeze_start.astimezone(tz)
        clusters = sorted({cl for s in (c.sites or list(site_clusters)) for cl in site_clusters.get(s, [])})
        out.append(
            {
                "kind": "deny",
                "schedule": _cron(start),
                "duration": _hours(c),
                "applications": ["*"],
                "clusters": clusters or ["*"],
                "manualSync": False,
                "timeZone": w.timezone,
            }
        )
    return out


def argocd_project(w: Windows, site_clusters: dict[str, list[str]], now: datetime, name: str = "platform") -> dict[str, Any]:
    return {
        "apiVersion": "argoproj.io/v1alpha1",
        "kind": "AppProject",
        "metadata": {"name": name, "namespace": "argocd"},
        "spec": {
            "description": "Platform services. Sync windows are generated by `runway freeze argocd` from config/launch-calendar.yaml.",
            "sourceRepos": ["*"],
            "destinations": [{"server": "*", "namespace": "*"}],
            "clusterResourceWhitelist": [{"group": "*", "kind": "*"}],
            "syncWindows": argocd_sync_windows(w, site_clusters, now),
        },
    }


def gitlab_freeze_periods(w: Windows, now: datetime) -> list[dict[str, str]]:
    """Bodies for POST /projects/:id/freeze_periods; GitLab sets CI_DEPLOY_FREEZE inside them."""
    tz = ZoneInfo(w.timezone)
    return [
        {
            "freeze_start": _cron(c.freeze_start.astimezone(tz)),
            "freeze_end": _cron(c.freeze_end.astimezone(tz)),
            "cron_timezone": w.timezone,
        }
        for c in sorted(w.campaigns, key=lambda c: c.freeze_start)
        if c.freeze_end > now
    ]


def check(w: Windows, site: str, at: datetime) -> Campaign | None:
    for c in calendar.active_freezes(w, at):
        if not c.sites or site in c.sites:
            return c
    return None
